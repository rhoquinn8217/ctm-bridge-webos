/* read off the pad on its cable: timer 0x36, battery 0x91, the charging-grip bit,
 * both sticks near their centres, the vibrator byte; presses added on B, Home
 * and down, and four motion bytes to see kept */
static const uint8_t k_full[17] = {
    0x30, 0x36, 0x91, 0x04, 0x90, 0x01, 0xb4, 0x97, 0x78, 0x40, 0x67, 0x7a, 0x0c,
    0x11, 0x22, 0x33, 0x44,
};

static void test_pro_controller(void)
{
    ok(pad_blank_from_descriptor(k_pro, sizeof(k_pro), 0x057e, 0x2009, &plan),
       "a Pro Controller gets a blank");
    ok(plan.switch_layout, "by the Switch layout for its full reports");
    ok(plan.count == 21, "and 21 described fields, all in 0x3F: 16 buttons, the hat, four sticks");

    uint8_t r[17];
    memcpy(r, k_full, sizeof(r));
    pad_blank_apply(&plan, r, sizeof(r));
    ok(r[1] == 0x36 && r[2] == 0x91, "0x30: the timer and the battery are kept");
    ok(r[3] == 0x00 && r[5] == 0x00, "0x30: the right and left buttons are up");
    ok(r[4] == 0x80, "0x30: Home is up and the charging-grip bit is kept");
    ok(r[6] == 0x00 && r[7] == 0x08 && r[8] == 0x80, "0x30: the left stick at 0x800, 0x800");
    ok(r[9] == 0x00 && r[10] == 0x08 && r[11] == 0x80, "0x30: the right stick at 0x800, 0x800");
    ok(r[12] == 0x0c && r[13] == 0x11 && r[16] == 0x44, "0x30: the vibrator byte and motion are kept");

    uint8_t reply[17] = { 0x21, 0x3a, 0x91, 0x08, 0x80, 0x00, 0xb4, 0x97, 0x78,
                          0x40, 0x67, 0x7a, 0x0c, 0x80, 0x48, 0x01, 0x00 };
    pad_blank_apply(&plan, reply, sizeof(reply));
    ok(reply[3] == 0x00 && reply[7] == 0x08, "0x21: a subcommand reply's buttons and sticks are blanked");
    ok(reply[13] == 0x80 && reply[14] == 0x48 && reply[15] == 0x01, "0x21: the reply itself is kept");

    uint8_t simple[12] = { 0x3F, 0xFF, 0xFF, 0x02, 0x00, 0x00, 0xFF, 0xFF, 0x12, 0x34, 0x56, 0x78 };
    pad_blank_apply(&plan, simple, sizeof(simple));
    ok(simple[1] == 0x00 && simple[2] == 0x00 && simple[3] == 0x08, "0x3F: buttons up, the hat at 8");
    ok(simple[4] == 0x00 && simple[5] == 0x80 && simple[6] == 0x00 && simple[7] == 0x80 &&
       simple[8] == 0x00 && simple[9] == 0x80 && simple[10] == 0x00 && simple[11] == 0x80,
       "0x3F: all four 16-bit sticks at 0x8000, by its descriptor");

    /* The same descriptor on a pad that is not a Pro Controller shows why the
     * layout is needed: 0x30's described buttons would land on the timer. */
    pad_blank_from_descriptor(k_pro, sizeof(k_pro), 0x1234, 0x2009, &plan);
    memcpy(r, k_full, sizeof(r));
    pad_blank_apply(&plan, r, sizeof(r));
    ok(!plan.switch_layout && r[1] == 0x00, "without the layout, the descriptor zeroes the timer byte");
}

static void test_what_cannot_be_read(void)
{
    const uint8_t cut[] = { 0x05, 0x01, 0x09, 0x05, 0xA1, 0x01, 0x85 };
    ok(!pad_blank_from_descriptor(cut, sizeof(cut), 0x1234, 0x0003, &plan), "a cut-off descriptor plans nothing");
    ok(!pad_blank_from_descriptor(NULL, 0, 0x1234, 0x0003, &plan), "no descriptor plans nothing");
    ok(pad_blank_from_descriptor(NULL, 0, 0x057e, 0x2009, &plan) && plan.switch_layout,
       "a Pro Controller with no descriptor still gets its own layout");
    const uint8_t vendor_only[] = {
        0x06, 0x00, 0xFF, 0x09, 0x01, 0xA1, 0x01, 0x15, 0x00, 0x26, 0xFF, 0x00,
        0x75, 0x08, 0x95, 0x10, 0x81, 0x02, 0xC0,
    };
    ok(!pad_blank_from_descriptor(vendor_only, sizeof(vendor_only), 0x1234, 0x0004, &plan),
       "a vendor-only device plans nothing");
    uint8_t r[4] = { 1, 2, 3, 4 };
    pad_blank_apply(&plan, r, sizeof(r));
    ok(r[0] == 1 && r[3] == 4, "and its reports pass as they came");
}


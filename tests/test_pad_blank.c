/* Tests for the overlay's blank built from a gamepad's report descriptor, and
 * the Pro Controller's own layout.
 *
 * ⭐⭐ WHY THIS EXISTS. A wrong blank does not fail loudly. It holds a button
 * down behind the overlay, pushes a stick into a corner, reads a d-pad of 0 as
 * "up", or writes over a Pro Controller's timer and battery. Every expectation
 * below is worked out from the HID usage tables, not from the code under test.
 *
 * ⓘ The descriptors are written for these tests in the layouts the pads use
 * (an Android-style pad, a signed joystick, a pad with a keyboard beside it, a
 * Pro Controller's reports); the Pro Controller's report bytes were read off the
 * real pad on the U5s (2026-09-16). Real descriptors from the field join these
 * from the core's log ("descriptor 000: ...").
 *
 * ➡️ Build and run:  cc tests/test_pad_blank.c && ./a.out
 *    Or:             ./tests/run-tests.sh
 */

#include <stdio.h>
#include <string.h>

#include "../src/controllers/pad_blank.inl"

static int checks, failed;

static void ok(int cond, const char *what)
{
    ++checks;
    if (!cond) { ++failed; printf("  FAIL  %s\n", what); }
    else       {           printf("  ok    %s\n", what); }
}

static pad_blank_plan_t plan;   /* big; one at a time is enough */

/* ---- an Android-style pad: buttons, hat, four 8-bit sticks, two triggers,
 * a Home button, report id 1 ---- */
static const uint8_t k_android[] = {
    0x05, 0x01, 0x09, 0x05, 0xA1, 0x01, 0x85, 0x01,
    0x05, 0x09, 0x19, 0x01, 0x29, 0x10, 0x15, 0x00, 0x25, 0x01,
    0x75, 0x01, 0x95, 0x10, 0x81, 0x02,                         /* 16 buttons: bytes 1-2 */
    0x05, 0x01, 0x09, 0x39, 0x15, 0x00, 0x25, 0x07,
    0x75, 0x04, 0x95, 0x01, 0x81, 0x42,                         /* hat 0-7: byte 3 low nibble */
    0x75, 0x04, 0x95, 0x01, 0x81, 0x03,                         /* padding: byte 3 high nibble */
    0x09, 0x30, 0x09, 0x31, 0x09, 0x32, 0x09, 0x35,
    0x15, 0x00, 0x26, 0xFF, 0x00, 0x75, 0x08, 0x95, 0x04, 0x81, 0x02,   /* X Y Z Rz: bytes 4-7 */
    0x05, 0x02, 0x09, 0xC5, 0x09, 0xC4, 0x95, 0x02, 0x81, 0x02, /* brake, accelerator: 8-9 */
    0x05, 0x0C, 0x0A, 0x23, 0x02, 0x15, 0x00, 0x25, 0x01,
    0x75, 0x01, 0x95, 0x01, 0x81, 0x02,                         /* AC Home: byte 10 bit 0 */
    0x75, 0x07, 0x95, 0x01, 0x81, 0x03,                         /* padding: byte 10 bits 1-7 */
    0xC0,
};

static void test_android_pad(void)
{
    ok(pad_blank_from_descriptor(k_android, sizeof(k_android), 0x3537, 0x1234, &plan),
       "an Android-style pad gets a blank");
    ok(plan.ids_used && !plan.switch_layout && plan.count == 24,
       "24 fields: 16 buttons, the hat, four sticks, two triggers, Home");
    uint8_t r[11] = { 0x01, 0xFF, 0xFF, 0xA2, 0x00, 0xFF, 0x10, 0xF0, 0xFF, 0x80, 0xFF };
    pad_blank_apply(&plan, r, sizeof(r));
    ok(r[0] == 0x01, "the report id stays");
    ok(r[1] == 0x00 && r[2] == 0x00, "every button up");
    ok((r[3] & 0x0F) == 0x08, "the hat reads 8, nothing pressed (0 would be up)");
    ok((r[3] & 0xF0) == 0xA0, "the padding beside the hat is untouched");
    ok(r[4] == 0x80 && r[5] == 0x80 && r[6] == 0x80 && r[7] == 0x80, "all four sticks centred at 0x80");
    ok(r[8] == 0x00 && r[9] == 0x00, "both triggers released");
    ok(r[10] == 0xFE, "Home up, the padding bits beside it untouched");
    uint8_t other[3] = { 0x02, 0xAA, 0xBB };
    pad_blank_apply(&plan, other, sizeof(other));
    ok(other[1] == 0xAA && other[2] == 0xBB, "a report id the descriptor does not describe is left alone");
}

/* ---- a joystick with no report id: signed 16-bit X and Y, a hat from 1, four
 * buttons, two vendor bytes, a relative wheel ---- */
static const uint8_t k_joystick[] = {
    0x05, 0x01, 0x09, 0x04, 0xA1, 0x01,
    0x09, 0x30, 0x09, 0x31, 0x16, 0x00, 0x80, 0x26, 0xFF, 0x7F,
    0x75, 0x10, 0x95, 0x02, 0x81, 0x02,                         /* X Y: bytes 0-3 */
    0x09, 0x39, 0x15, 0x01, 0x25, 0x08, 0x75, 0x04, 0x95, 0x01, 0x81, 0x42,   /* hat 1-8 */
    0x05, 0x09, 0x19, 0x01, 0x29, 0x04, 0x15, 0x00, 0x25, 0x01,
    0x75, 0x01, 0x95, 0x04, 0x81, 0x02,                         /* 4 buttons: byte 4 high nibble */
    0x06, 0x00, 0xFF, 0x09, 0x01, 0x15, 0x00, 0x26, 0xFF, 0x00,
    0x75, 0x08, 0x95, 0x02, 0x81, 0x02,                         /* vendor: bytes 5-6 */
    0x05, 0x01, 0x09, 0x38, 0x15, 0x81, 0x25, 0x7F,
    0x75, 0x08, 0x95, 0x01, 0x81, 0x06,                         /* relative wheel: byte 7 */
    0xC0,
};

static void test_signed_joystick(void)
{
    ok(pad_blank_from_descriptor(k_joystick, sizeof(k_joystick), 0x1234, 0x5678, &plan),
       "a joystick with no report id gets a blank");
    ok(!plan.ids_used, "no report id");
    uint8_t r[8] = { 0x00, 0x80, 0xFF, 0x7F, 0xF3, 0x12, 0x34, 0x05 };
    pad_blank_apply(&plan, r, sizeof(r));
    ok(r[0] == 0x00 && r[1] == 0x00 && r[2] == 0x00 && r[3] == 0x00,
       "signed sticks centred at 0, not at 0x8000");
    ok(r[4] == 0x00, "the hat reads 0 below its 1-8 range, and the buttons are up");
    ok(r[5] == 0x12 && r[6] == 0x34, "the vendor bytes are left as they came");
    ok(r[7] == 0x00, "a relative axis rests at 0");
}


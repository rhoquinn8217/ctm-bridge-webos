static void test_real_pads_blank(void)
{
    ok(pad_blank_from_descriptor(k_xbox_bt, sizeof(k_xbox_bt), 0x045e, 0x0b20, &plan) &&
       plan.count == 23, "Xbox on Bluetooth: 23 fields, four sticks, two triggers, the hat, 15 buttons, record");
    /* as the pad sent it: both sticks pushed, both triggers pulled, the hat
     * right, A and B, record */
    uint8_t x[17] = { 0x01, 0xFF, 0xFF, 0x00, 0x00, 0x34, 0x12, 0x00, 0x80,
                      0xFF, 0x03, 0xFF, 0x03, 0x03, 0x03, 0x00, 0x01 };
    pad_blank_apply(&plan, x, sizeof(x));
    const uint8_t x_rest[17] = { 0x01, 0x00, 0x80, 0x00, 0x80, 0x00, 0x80, 0x00, 0x80,
                                 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00 };
    ok(memcmp(x, x_rest, sizeof(x)) == 0,
       "Xbox on Bluetooth: blanked to what its own blank makes (sticks 0x8000, the rest 0)");

    ok(pad_blank_from_descriptor(k_gamesir_bt, sizeof(k_gamesir_bt), 0x3537, 0x1108, &plan) &&
       plan.count == 23, "GameSir: 23 fields in its pad report, none in its media keys or keyboard");
    /* the pad's rest as it sends it: its hat padding reads 8 */
    uint8_t g[11] = { 0x07, 0x00, 0xFF, 0x80, 0x10, 0x82, 0x01, 0x80, 0xFF, 0x40, 0x88 };
    pad_blank_apply(&plan, g, sizeof(g));
    ok(g[1] == 0x80 && g[2] == 0x80 && g[3] == 0x80 && g[4] == 0x80, "GameSir: four sticks at 0x80");
    ok(g[5] == 0x88, "GameSir: the hat at 8, its padding as it came");
    ok(g[6] == 0x00 && g[7] == 0x00 && g[8] == 0x00 && g[9] == 0x00, "GameSir: buttons up, both triggers released");
    ok(g[10] == 0x88, "GameSir: the padding byte as it came");
    uint8_t media[3] = { 0x02, 0x04, 0x00 };
    pad_blank_apply(&plan, media, sizeof(media));
    ok(media[1] == 0x04, "GameSir: a media key report is not touched");

    ok(pad_blank_from_descriptor(k_pro_bt, sizeof(k_pro_bt), 0x057e, 0x2009, &plan) &&
       plan.switch_layout && plan.count == 21, "Pro Controller on Bluetooth: the Switch layout and 0x3F's 21 fields");
}

static pad_keep_t keep;

static void test_still_pads(void)
{
    uint8_t out[256];

    /* Two Bluetooth Xbox pads bridged from the panel and put down sent nothing,
     * so there was nothing to send again (2026-09-16). */
    pad_blank_from_descriptor(k_xbox_bt, sizeof(k_xbox_bt), 0x045e, 0x0b20, &plan);
    ok(plan.rest_id == 0x01 && plan.rest_len == 17, "Xbox on Bluetooth: rest report 0x01, 17 bytes");
    const uint8_t x_rest[17] = { 0x01, 0x00, 0x80, 0x00, 0x80, 0x00, 0x80, 0x00, 0x80,
                                 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00 };
    ok(pad_rest_report(&plan, out, sizeof(out)) == 17 && memcmp(out, x_rest, 17) == 0,
       "Xbox on Bluetooth: nothing pressed, sticks centred");
    ok(pad_rest_report(&plan, out, 16) == 0, "a rest report that does not fit is not made");

    pad_blank_from_descriptor(k_gamesir_bt, sizeof(k_gamesir_bt), 0x3537, 0x1108, &plan);
    ok(plan.rest_id == 0x07 && plan.rest_len == 11, "GameSir: rest report 0x07, 11 bytes");
    const uint8_t g_rest[11] = { 0x07, 0x80, 0x80, 0x80, 0x80, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00 };
    memset(&keep, 0, sizeof(keep));
    ok(pad_keep_current(&keep, &plan, out, sizeof(out)) == 11 && memcmp(out, g_rest, 11) == 0,
       "GameSir: before it sends anything, the rest report");
    const uint8_t g_held[11] = { 0x07, 0x80, 0x80, 0x30, 0x80, 0x88, 0x01, 0x00, 0x00, 0xFF, 0x00 };
    pad_keep_update(&keep, &plan, g_held, sizeof(g_held));
    ok(pad_keep_current(&keep, &plan, out, sizeof(out)) == 11 && memcmp(out, g_held, 11) == 0,
       "GameSir: then its own last report, with A and a trigger still held");
    const uint8_t media[3] = { 0x02, 0x04, 0x00 };
    const uint8_t kbd[9] = { 0x01, 0x00, 0x00, 0x04, 0x00, 0x00, 0x00, 0x00, 0x00 };
    pad_keep_update(&keep, &plan, media, sizeof(media));
    pad_keep_update(&keep, &plan, kbd, sizeof(kbd));
    ok(pad_keep_current(&keep, &plan, out, sizeof(out)) == 11 && memcmp(out, g_held, 11) == 0,
       "GameSir: a media key or keyboard report is never sent again");
    uint8_t too_long[PAD_KEEP_MAX + 1];
    memset(too_long, 0, sizeof(too_long));
    too_long[0] = 0x07;
    pad_keep_update(&keep, &plan, too_long, sizeof(too_long));
    ok(pad_keep_current(&keep, &plan, out, sizeof(out)) == 0,
       "a pad report too long to keep ends the keepalive, rather than send an older one");

    pad_blank_from_descriptor(k_pro_bt, sizeof(k_pro_bt), 0x057e, 0x2009, &plan);
    memset(&keep, 0, sizeof(keep));
    const uint8_t simple[12] = { 0x3F, 0x00, 0x00, 0x08, 0x00, 0x80, 0x00, 0x80, 0x00, 0x80, 0x00, 0x80 };
    pad_keep_update(&keep, &plan, simple, sizeof(simple));
    ok(plan.rest_len == 0 && pad_keep_current(&keep, &plan, out, sizeof(out)) == 0,
       "Pro Controller: nothing is sent again, it never goes quiet");

    pad_blank_from_descriptor(k_android, sizeof(k_android), 0x3537, 0x1234, &plan);
    const uint8_t a_rest[11] = { 0x01, 0x00, 0x00, 0x08, 0x80, 0x80, 0x80, 0x80, 0x00, 0x00, 0x00 };
    ok(pad_rest_report(&plan, out, sizeof(out)) == 11 && memcmp(out, a_rest, 11) == 0,
       "Android-style pad: the hat at 8, sticks at 0x80, Home up");

    pad_blank_from_descriptor(k_pad_and_keyboard, sizeof(k_pad_and_keyboard), 0x1234, 0x0001, &plan);
    ok(plan.rest_id == 0x01 && plan.rest_len == 2, "a pad beside a keyboard: the pad's report, not the keyboard's");

    /* A relative wheel sent again would turn again. */
    pad_blank_from_descriptor(k_joystick, sizeof(k_joystick), 0x1234, 0x5678, &plan);
    ok(!plan.ids_used && plan.rest_len == 8 && plan.rel_count == 1, "joystick: 8 bytes, no id, one relative field");
    memset(&keep, 0, sizeof(keep));
    const uint8_t j[8] = { 0x00, 0x80, 0xFF, 0x7F, 0xF3, 0x12, 0x34, 0x05 };
    pad_keep_update(&keep, &plan, j, sizeof(j));
    ok(pad_keep_current(&keep, &plan, out, sizeof(out)) == 8 &&
       memcmp(out, j, 7) == 0 && out[7] == 0x00,
       "joystick: sent again with the sticks, hat, buttons and vendor bytes as kept, and the wheel at 0");

    const uint8_t many_relative[] = {
        0x05, 0x01, 0x09, 0x05, 0xA1, 0x01, 0x85, 0x01,
        0x05, 0x09, 0x19, 0x01, 0x29, 0x08, 0x15, 0x00, 0x25, 0x01,
        0x75, 0x01, 0x95, 0x08, 0x81, 0x02,
        0x05, 0x01, 0x09, 0x38, 0x15, 0x81, 0x25, 0x7F,
        0x75, 0x08, 0x95, 0x11, 0x81, 0x06,                     /* 17 relative bytes */
        0xC0,
    };
    pad_blank_from_descriptor(many_relative, sizeof(many_relative), 0x1234, 0x0005, &plan);
    ok(plan.rel_overflow && plan.rest_len == 0, "more relative fields than fit: no keepalive at all");
}


static void test_the_keyboard_beside_a_pad(void)
{
    pad_blank_from_descriptor(k_pad_and_keyboard, sizeof(k_pad_and_keyboard), 0x1234, 0x0001, &plan);
    ok(plan.count == 8, "only the pad's eight buttons are planned");
    uint8_t pad[2] = { 0x01, 0xFF };
    pad_blank_apply(&plan, pad, sizeof(pad));
    ok(pad[1] == 0x00, "the pad's buttons are released");
    uint8_t kbd[8] = { 0x02, 0x05, 0x00, 0x04, 0x00, 0x00, 0x00, 0x00 };
    const uint8_t before[8] = { 0x02, 0x05, 0x00, 0x04, 0x00, 0x00, 0x00, 0x00 };
    pad_blank_apply(&plan, kbd, sizeof(kbd));
    ok(memcmp(kbd, before, sizeof(kbd)) == 0, "the keyboard's report is not touched");
}

